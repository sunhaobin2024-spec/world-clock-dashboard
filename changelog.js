//   添加新功能 -> 版本号 +1    （例 v3.2 -> v4.2）
//   修复功能   -> 版本号 +0.1  （例 v4.2 -> v4.3）
//   优化内容   -> 版本号 +0.01 （例 v4.2 -> v4.21）
//   每次发版调用 bumpVersion('feature'|'fix'|'opt', 当前版本) 自动算下一版本。
// ============================================================
// 版本号自动累加（按上述政策）。feature 在整数部分加 1，fix 加 0.1，opt 加 0.01。
function bumpVersion(kind, cur){
  const base = parseFloat(String(cur).replace(/^v/,'')) || 0;
  const delta = kind==='feature' ? 1 : kind==='fix' ? 0.1 : kind==='opt' ? 0.01 : 0;
  const v = +(base + delta).toFixed(2);
  return 'v' + (Number.isInteger(v) ? v + '.0' : v);
}
